/// How wide `text` is, in font pixels.
pub fn width(text: &str) -> usize {
    text.chars().count().saturating_mul(ADVANCE).saturating_sub(1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_attribution_character_has_a_glyph() {
        for b in mkaegis_model::Basemap::ALL {
            let text = crate::basemap::source(b).export_attribution;
            for c in text.chars().filter(|c| *c != ' ') {
                assert!(glyph(c).iter().any(|row| *row != 0), "{c:?} in {text:?}");
            }
        }
        assert!(glyph('ü').iter().all(|row| *row == 0), "unknown characters are blank");
        assert!(glyph('W').iter().all(|row| *row < 32), "five bits wide");
    }
}
